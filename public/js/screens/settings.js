const { makeT } = AS
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')

// ---- Google Identity Services ("Sign in with Google") ----
// The client ID is fetched once from the backend (/auth/config). When it is blank
// the Google button is simply not rendered (email + password only).
let gsiClientId = null   // null = not fetched yet; '' = not configured
let gsiScript = null
let gsiInitialized = false   // google.accounts.id.initialize must run at most once
function loadGsiScript() {
  if (window.google && window.google.accounts && window.google.accounts.id) return Promise.resolve()
  if (gsiScript) return gsiScript
  gsiScript = new Promise(resolve => {
    const s = document.createElement('script')
    s.src = 'https://accounts.google.com/gsi/client'
    s.async = true; s.defer = true
    s.onload = () => resolve()
    s.onerror = () => { gsiScript = null; resolve() }
    document.head.appendChild(s)
  })
  return gsiScript
}
async function mountGoogle(container, app, tt) {
  if (gsiClientId === null) {
    try { const cfg = await app.authConfig(); gsiClientId = (cfg && cfg.googleClientId) || '' }
    catch (e) { gsiClientId = '' }
  }
  if (!gsiClientId) return
  const el = container.querySelector('#googleBtn')
  if (!el) return
  await loadGsiScript()
  const g = window.google && window.google.accounts && window.google.accounts.id
  if (!g || !g.renderButton) return
  // Initialize once. Re-running it on every redraw logs a GSI warning and can
  // leave a stale callback bound to a detached container.
  if (!gsiInitialized) {
    g.initialize({
      client_id: gsiClientId,
      auto_select: false,
      cancel_on_tap_outside: true,
      error_callback: () => {},
      callback: async response => {
        if (!response || !response.credential) return
        const problem = await app.loginGoogle(response.credential).catch(() => 'network')
        if (problem) {
          const err = container.querySelector('#loginErr')
          if (err) err.textContent = tt('auth_err_google')
        }
      }
    })
    gsiInitialized = true
  }
  el.innerHTML = ''
  try {
    g.renderButton(el, { theme: 'outline', size: 'large', text: 'signin_with', shape: 'pill', width: 300 })
  } catch (e) { /* button render is best-effort; email/phone login still works */ }
}

// ---- 6-digit passcode keypad (used by the phone login screen) ----
function pinPadHtml() {
  const cells = ['1', '2', '3', '4', '5', '6', '7', '8', '9', '', '0', 'del']
  const keys = cells.map(k =>
    k === '' ? '<span class="pin-key blank"></span>'
    : k === 'del' ? '<button type="button" class="pin-key del" data-k="del" aria-label="delete">⌫</button>'
    : `<button type="button" class="pin-key" data-k="${k}">${k}</button>`).join('')
  return `<div class="pin-wrap"><div class="pin-dots">${'<i></i>'.repeat(6)}</div><div class="pin-pad">${keys}</div></div>`
}
function wirePinPad(container, getValue, setValue) {
  const dots = Array.prototype.slice.call(container.querySelectorAll('.pin-dots i'))
  const paint = () => { const v = getValue(); dots.forEach((d, i) => d.classList.toggle('on', i < v.length)) }
  container.querySelectorAll('.pin-key[data-k]').forEach(k => {
    k.onclick = () => {
      const key = k.dataset.k
      let v = getValue()
      if (key === 'del') v = v.slice(0, -1)
      else if (v.length < 6) v += key
      setValue(v)
      paint()
    }
  })
  paint()
}


AS.renderLogin = function (container, app) {
  // The admin tab is not public: it only appears at the /agro_admin path.
  const IS_ADMIN = /\/agro_admin\/?$/.test(location.pathname) || location.hash.indexOf('agro_admin') >= 0
  let mode = IS_ADMIN ? 'admin' : 'login'   // login | email | register | admin | reset
  let regStep = 1                            // register: 1 = ID+phone, 2 = passcode
  const draft = { tel: '', pin: '', email: '', epass: '', name: '', id: '', phone: '' }
  const errMap = {
    notfound: 'auth_err_notfound', exists: 'auth_err_exists', exists_id: 'auth_err_exists_id',
    bad_id: 'auth_err_bad_id', badpin: 'auth_err_badpin', badpass: 'auth_err_badpass',
    weak: 'auth_err_weak', bad_email: 'login_err_email', bad_phone: 'login_err_phone',
    google_only: 'auth_err_google_only', network: 'auth_err_network', mismatch: 'auth_err_mismatch'
  }
  const PHONE_OK = /^(\+?250|0)7\d{8}$/
  // Forgot-password flow state
  let resetStep = 1          // 1 = phone, 2 = OTP, 3 = new password
  let resetPhone = ''
  let resetToken = ''
  let resetCode = ''         // OTP generated by the server, shown in-app (no SMS)

  // Shared chrome: language corner + optional Login/Register tabs.
  const frame = (tt, lg, sub, tabs, body) => `
    <div class="login">
      <button class="corner-lang" id="langCorner">${lg === 'rw' ? 'EN' : 'RW'}</button>
      <img class="logo" src="icon.png" alt="AgroSmart Rwanda" />
      <h1>${tt('appName')}</h1>
      <p class="tagline">${sub}</p>
      ${tabs || ''}
      <div class="auth-card">${body}</div>
    </div>`
  const tabsHtml = (tt, active) => IS_ADMIN ? '' : `
    <div class="auth-tabs">
      <button class="auth-tab ${active === 'login' ? 'active' : ''}" id="tabLogin">${tt('auth_tab_login')}</button>
      <button class="auth-tab ${active === 'register' ? 'active' : ''}" id="tabSignup">${tt('auth_tab_signup')}</button>
    </div>`
  // Read the on-screen inputs back into draft before any redraw.
  const capture = () => {
    const q = id => { const e = container.querySelector(id); return e ? e.value : null }
    const tel = q('#loginTel'); if (tel !== null) draft.tel = tel
    const em = q('#loginEmail'); if (em !== null) draft.email = em
    const ep = q('#loginPass'); if (ep !== null) draft.epass = ep
    const nm = q('#loginName'); if (nm !== null) draft.name = nm
    const idn = q('#regId'); if (idn !== null) draft.id = idn
    const rp = q('#regPhone'); if (rp !== null) draft.phone = rp
  }
  const wireCommon = () => {
    const lc = container.querySelector('#langCorner')
    if (lc) lc.onclick = () => { capture(); app.setLang((app.lang || 'rw') === 'rw' ? 'en' : 'rw') }
    const tl = container.querySelector('#tabLogin'); if (tl) tl.onclick = () => { capture(); mode = 'login'; draw() }
    const ts = container.querySelector('#tabSignup'); if (ts) ts.onclick = () => { capture(); mode = 'register'; regStep = 1; draw() }
  }

  const draw = () => {
    const lg = app.lang || 'rw'
    const tt = makeT(lg)

    if (mode === 'reset') { drawReset(tt, lg); return }
    if (mode === 'admin') { drawAdmin(tt, lg); return }
    if (mode === 'email') { drawEmail(tt, lg); return }
    if (mode === 'register') { drawRegister(tt, lg); return }
    drawLogin(tt, lg)
  }

  // Login: mobile number + 6-digit passcode keypad, Google, email fallback.
  const drawLogin = (tt, lg) => {
    container.innerHTML = frame(tt, lg, tt('auth_login_sub'), tabsHtml(tt, 'login'), `
      <div class="field">
        <img class="f-ico" src="img/phone.png" alt="">
        <input id="loginTel" type="tel" inputmode="numeric" autocomplete="tel" placeholder="${tt('login_tel')}" value="${esc(draft.tel)}" />
      </div>
      <div class="pin-label">${tt('login_passcode')}</div>
      ${pinPadHtml()}
      <div class="err" id="loginErr"></div>
      <button class="btn btn-primary" id="loginBtn">${tt('login_btn')} →</button>
      <button class="link-btn" id="forgotBtn">${tt('login_forgot')}</button>
      <div class="auth-or"><span>${tt('auth_or')}</span></div>
      <div class="google-wrap"><div id="googleBtn"></div></div>
      <button class="link-btn subtle" id="emailFallback">${tt('auth_email_fallback')}</button>`)
    wireCommon()
    wirePinPad(container, () => draft.pin, v => { draft.pin = v })
    container.querySelector('#forgotBtn').onclick = () => { capture(); resetPhone = draft.tel; resetStep = 1; mode = 'reset'; draw() }
    container.querySelector('#emailFallback').onclick = () => { capture(); mode = 'email'; draw() }
    mountGoogle(container, app, tt)
    container.querySelector('#loginBtn').onclick = async () => {
      capture()
      const err = container.querySelector('#loginErr'); err.textContent = ''
      const tel = draft.tel.replace(/[\s-]/g, '')
      if (!PHONE_OK.test(tel)) { err.textContent = tt('login_err_phone'); return }
      if (!/^\d{6}$/.test(draft.pin)) { err.textContent = tt('login_err_passcode'); return }
      const btn = container.querySelector('#loginBtn'); btn.disabled = true
      let problem
      try { problem = await app.loginPhone(tel, draft.pin) } catch (e) { problem = 'network' }
      btn.disabled = false
      if (!problem) return
      err.textContent = tt(errMap[problem] || 'auth_err_generic')
    }
  }

  // Fallback for pre-existing email + password accounts.
  const drawEmail = (tt, lg) => {
    container.innerHTML = frame(tt, lg, tt('login_sub'), tabsHtml(tt, 'login'), `
      <div class="field">
        <img class="f-ico" src="img/id-card.png" alt="">
        <input id="loginEmail" type="email" inputmode="email" autocomplete="username" placeholder="${tt('login_email')}" value="${esc(draft.email)}" />
      </div>
      <div class="field">
        <img class="f-ico" src="img/settings.png" alt="">
        <input id="loginPass" type="password" autocomplete="current-password" placeholder="${tt('login_password')}" value="${esc(draft.epass)}" />
      </div>
      <div class="err" id="loginErr"></div>
      <button class="btn btn-primary" id="loginBtn">${tt('login_btn')} →</button>
      <button class="link-btn" id="emailBack">${tt('auth_email_back')}</button>
      <div class="auth-or"><span>${tt('auth_or')}</span></div>
      <div class="google-wrap"><div id="googleBtn"></div></div>`)
    wireCommon()
    container.querySelector('#emailBack').onclick = () => { capture(); mode = 'login'; draw() }
    mountGoogle(container, app, tt)
    container.querySelector('#loginBtn').onclick = async () => {
      capture()
      const err = container.querySelector('#loginErr'); err.textContent = ''
      const email = draft.email.trim()
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) { err.textContent = tt('login_err_email'); return }
      if (!draft.epass) { err.textContent = tt('login_err_pass'); return }
      const btn = container.querySelector('#loginBtn'); btn.disabled = true
      let problem
      try { problem = await app.login(email, draft.epass) } catch (e) { problem = 'network' }
      btn.disabled = false
      if (!problem) return
      err.textContent = tt(errMap[problem] || 'auth_err_generic')
    }
  }

  // Register: step 1 National ID + mobile (+ optional name), step 2 create passcode.
  const drawRegister = (tt, lg) => {
    if (regStep === 1) {
      container.innerHTML = frame(tt, lg, tt('auth_reg_sub'), tabsHtml(tt, 'register'), `
        <div class="field">
          <img class="f-ico" src="img/id-card.png" alt="">
          <input id="regId" type="text" inputmode="numeric" maxlength="16" autocomplete="off" placeholder="${tt('login_id')}" value="${esc(draft.id)}" />
        </div>
        <div class="field">
          <img class="f-ico" src="img/phone.png" alt="">
          <input id="regPhone" type="tel" inputmode="numeric" autocomplete="tel" placeholder="${tt('login_phone')}" value="${esc(draft.phone)}" />
        </div>
        <div class="field">
          <img class="f-ico" src="img/user.png" alt="">
          <input id="loginName" type="text" autocomplete="name" placeholder="${tt('login_name')}" value="${esc(draft.name)}" />
        </div>
        <div class="err" id="loginErr"></div>
        <button class="btn btn-primary" id="regNext">${tt('auth_reg_btn')} →</button>
        <p class="auth-hint">${tt('auth_reg_google_sub')}</p>
        <div class="google-wrap"><div id="googleBtn"></div></div>`)
      wireCommon()
      mountGoogle(container, app, tt)
      container.querySelector('#regNext').onclick = () => {
        capture()
        const err = container.querySelector('#loginErr'); err.textContent = ''
        if (!/^\d{16}$/.test(draft.id.trim())) { err.textContent = tt('auth_err_bad_id'); return }
        if (!PHONE_OK.test(draft.phone.replace(/[\s-]/g, ''))) { err.textContent = tt('login_err_phone'); return }
        draft.id = draft.id.trim(); draft.phone = draft.phone.replace(/[\s-]/g, '')
        regStep = 2; draw()
      }
      return
    }
    container.innerHTML = frame(tt, lg, tt('auth_reg_step2'), tabsHtml(tt, 'register'), `
      <div class="field">
        <img class="f-ico" src="img/settings.png" alt="">
        <input id="regPin" type="password" inputmode="numeric" maxlength="6" autocomplete="new-password" placeholder="${tt('auth_reg_passcode')}" />
      </div>
      <div class="field">
        <img class="f-ico" src="img/settings.png" alt="">
        <input id="regPin2" type="password" inputmode="numeric" maxlength="6" autocomplete="new-password" placeholder="${tt('auth_reg_confirm')}" />
      </div>
      <div class="err" id="loginErr"></div>
      <button class="btn btn-primary" id="regCreate">${tt('auth_signup_btn')} →</button>
      <button class="link-btn" id="regBack">${tt('reset_back')}</button>`)
    wireCommon()
    container.querySelector('#regBack').onclick = () => { regStep = 1; draw() }
    container.querySelector('#regCreate').onclick = async () => {
      const err = container.querySelector('#loginErr'); err.textContent = ''
      const p1 = container.querySelector('#regPin').value
      const p2 = container.querySelector('#regPin2').value
      if (!/^\d{6}$/.test(p1)) { err.textContent = tt('login_err_passcode'); return }
      if (p1 !== p2) { err.textContent = tt('auth_err_mismatch'); return }
      const btn = container.querySelector('#regCreate'); btn.disabled = true
      let problem
      try { problem = await app.register(draft.id, draft.phone, p1, draft.name.trim()) } catch (e) { problem = 'network' }
      btn.disabled = false
      if (!problem) return
      err.textContent = tt(errMap[problem] || 'auth_err_generic')
    }
  }

  // Admin sign-in — only reachable at /agro_admin. Email + password, admin role.
  const drawAdmin = (tt, lg) => {
    container.innerHTML = frame(tt, lg, tt('auth_admin_sub'), '', `
      <div class="field">
        <img class="f-ico" src="img/id-card.png" alt="">
        <input id="loginEmail" type="email" inputmode="email" autocomplete="username" placeholder="${tt('login_email')}" value="${esc(draft.email)}" />
      </div>
      <div class="field">
        <img class="f-ico" src="img/settings.png" alt="">
        <input id="loginPass" type="password" autocomplete="current-password" placeholder="${tt('login_password')}" value="${esc(draft.epass)}" />
      </div>
      <div class="err" id="loginErr"></div>
      <button class="btn btn-primary" id="loginBtn">${tt('auth_admin_btn')} →</button>
      <p class="auth-hint">${tt('auth_hint_admin')}</p>`)
    wireCommon()
    container.querySelector('#loginBtn').onclick = async () => {
      capture()
      const err = container.querySelector('#loginErr'); err.textContent = ''
      const email = draft.email.trim()
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) { err.textContent = tt('login_err_email'); return }
      if (!draft.epass) { err.textContent = tt('login_err_pass'); return }
      const btn = container.querySelector('#loginBtn'); btn.disabled = true
      let problem
      try { problem = await app.loginAdmin(email, draft.epass) } catch (e) { problem = 'network' }
      btn.disabled = false
      if (!problem) return
      err.textContent = tt(errMap[problem] || 'auth_err_generic')
    }
  }

  // Multi-step "Forgot password" card: phone → OTP → new 6-digit password.
  const drawReset = (tt, lg) => {
    container.innerHTML = `
      <div class="login">
        <button class="corner-lang" id="langCorner">${lg === 'rw' ? 'EN' : 'RW'}</button>
        <img class="logo" src="icon.png" alt="AgroSmart Rwanda" />
        <h1>${tt('reset_title')}</h1>
        <p class="tagline">${tt(resetStep === 1 ? 'reset_phone_step' : resetStep === 2 ? 'reset_otp_step' : 'reset_new_step')}</p>
        <div class="auth-card">
          ${resetStep === 1 ? `
            <div class="field">
              <img class="f-ico" src="img/phone.png" alt="">
              <input id="rsPhone" type="tel" inputmode="numeric" autocomplete="tel" placeholder="${tt('login_phone')}" value="${esc(resetPhone)}" />
            </div>` : ''}
          ${resetStep === 2 ? `
            ${resetCode ? `<div class="otp-box"><span class="otp-label">${tt('reset_demo_code')}</span><span class="otp-code">${esc(resetCode)}</span></div>` : ''}
            <div class="field">
              <img class="f-ico" src="img/settings.png" alt="">
              <input id="rsOtp" type="tel" inputmode="numeric" maxlength="6" autocomplete="one-time-code" placeholder="${tt('reset_otp_label')}" />
            </div>` : ''}
          ${resetStep === 3 ? `
            <div class="field">
              <img class="f-ico" src="img/settings.png" alt="">
              <input id="rsPass" type="password" inputmode="numeric" maxlength="6" autocomplete="new-password" placeholder="${tt('reset_new_label')}" />
            </div>
            <div class="field">
              <img class="f-ico" src="img/settings.png" alt="">
              <input id="rsPass2" type="password" inputmode="numeric" maxlength="6" autocomplete="new-password" placeholder="${tt('reset_confirm_label')}" />
            </div>` : ''}
          <div class="err" id="rsErr"></div>
          <button class="btn btn-primary" id="rsBtn">${tt(resetStep === 1 ? 'reset_send_otp' : resetStep === 2 ? 'reset_verify' : 'reset_submit')} →</button>
          ${resetStep === 2 ? `<button class="link-btn" id="rsResend">${tt('reset_resend')}</button>` : ''}
          <button class="link-btn" id="rsBack">${tt('reset_back')}</button>
        </div>
      </div>`

    const err = container.querySelector('#rsErr')
    const btn = container.querySelector('#rsBtn')
    container.querySelector('#langCorner').onclick = () => {
      if (resetStep === 1) resetPhone = container.querySelector('#rsPhone').value
      draw()
    }
    container.querySelector('#rsBack').onclick = () => {
      mode = 'login'; resetStep = 1; resetToken = ''; resetCode = ''; draft.tel = resetPhone; draft.pin = ''; draw()
    }
    const resend = container.querySelector('#rsResend')
    if (resend) resend.onclick = () => sendOtp(true)

    async function sendOtp(isResend) {
      const phone = (container.querySelector('#rsPhone') ? container.querySelector('#rsPhone').value : resetPhone).replace(/[\s-]/g, '')
      err.textContent = ''
      if (!/^(\+?250|0)7\d{8}$/.test(phone)) { err.textContent = tt('login_err_phone'); return }
      btn.disabled = true
      const r = await app.forgotPassword(phone).catch(() => ({ error: 'network' }))
      btn.disabled = false
      const problem = r && r.error
      if (problem === 'too_soon' && !isResend) { err.textContent = tt('reset_err_too_soon'); return }
      if (problem) {
        err.textContent = tt(problem === 'notfound' ? 'reset_err_notfound'
          : problem === 'too_soon' ? 'reset_err_too_soon'
          : problem === 'network' ? 'auth_err_network' : 'auth_err_generic')
        return
      }
      resetPhone = phone; resetCode = r.code || ''; resetStep = 2; draw()
    }

    btn.onclick = async () => {
      err.textContent = ''
      if (resetStep === 1) { return sendOtp(false) }
      if (resetStep === 2) {
        const code = container.querySelector('#rsOtp').value.trim()
        if (!/^\d{6}$/.test(code)) { err.textContent = tt('reset_err_otp_wrong'); return }
        btn.disabled = true
        const r = await app.verifyOtp(resetPhone, code).catch(() => ({ error: 'network' }))
        btn.disabled = false
        if (r.error) {
          err.textContent = tt(r.error === 'otp_wrong' ? 'reset_err_otp_wrong'
            : r.error === 'otp_expired' ? 'reset_err_otp_expired'
            : r.error === 'network' ? 'auth_err_network' : 'auth_err_generic')
          return
        }
        resetToken = r.token; resetStep = 3; draw()
        return
      }
      // step 3 — set the new password
      const p1 = container.querySelector('#rsPass').value
      const p2 = container.querySelector('#rsPass2').value
      if (!/^\d{6}$/.test(p1)) { err.textContent = tt('reset_err_six'); return }
      if (p1 !== p2) { err.textContent = tt('reset_err_mismatch'); return }
      btn.disabled = true
      const problem = await app.resetPassword(resetToken, p1).catch(() => 'network')
      btn.disabled = false
      if (problem === 'expired') { err.textContent = tt('reset_err_otp_expired'); resetStep = 1; resetToken = ''; resetCode = ''; return }
      if (problem) {
        err.textContent = tt(problem === 'six' ? 'reset_err_six'
          : problem === 'network' ? 'auth_err_network' : 'auth_err_generic')
        return
      }
      // Success: return to login with a confirmation.
      mode = 'login'; resetStep = 1; resetToken = ''; resetCode = ''; draft.tel = resetPhone; draft.pin = ''
      draw()
      const note = container.querySelector('#loginErr')
      if (note) { note.className = 'err ok'; note.textContent = tt('reset_success') }
    }
  }

  draw()
}

